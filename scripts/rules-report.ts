// Runs the 40 September enquiries through the rule engine and writes docs/rules_report.md.
// Usage: npm run rules:report
import { writeFileSync } from "node:fs";
import { evaluate } from "../lib/rules/engine";
import { FIXTURES } from "../tests/fixtures/sep2026";

const OUTCOME_LABEL: Record<string, string> = {
  qualified: "✅ Qualified",
  not_qualified: "❌ Not qualified",
  needs_review: "🟡 Needs review",
  not_a_lead: "⚪ Not a lead",
};
const DECIDED_LABEL: Record<string, string> = {
  all_pass: "All criteria pass",
  service_area: "Outside service area",
  real_project: "Not design + execution / unclear scope",
  timeline: "Deadline too soon",
  budget: "Budget clearly too low",
  excluded_type: "Excluded type (restaurant/gym…)",
  commercial_too_small: "Commercial space too small",
  incomplete: "Missed / incomplete call",
  existing_client_issue: "Existing client complaint → escalate",
};

let match = 0;
const rows = FIXTURES.map((f) => {
  const r = evaluate(f.input);
  const ok =
    r.outcome === f.expect.outcome &&
    r.decidedBy === f.expect.decidedBy &&
    (!f.expect.temperature || r.temperature === f.expect.temperature);
  if (ok) match++;
  const temp = r.outcome === "not_a_lead" ? "—" : r.temperature;
  return `| ${f.id} | ${f.channel} | ${OUTCOME_LABEL[r.outcome]} | ${temp} | ${DECIDED_LABEL[r.decidedBy] ?? r.decidedBy} | ${r.flags.join(", ") || "—"} | “${f.evidence.replace(/\|/g, "/")}” | ${ok ? "✔" : "✘"} |`;
});

const counts = FIXTURES.reduce<Record<string, number>>((acc, f) => {
  const o = evaluate(f.input).outcome;
  acc[o] = (acc[o] ?? 0) + 1;
  return acc;
}, {});

const md = `# Rules engine: results on the 40 September enquiries

Generated by \`npm run rules:report\`. Rules come from \`docs/functional_design.md\`.

**Agreement with the expected results: ${match} / ${FIXTURES.length}.**

| Outcome | Count |
|---|---|
${Object.entries(counts).map(([k, v]) => `| ${OUTCOME_LABEL[k]} | ${v} |`).join("\n")}

| ID | Channel | Outcome | Temp. | Decided by | Flags for designer | Evidence | Matches |
|---|---|---|---|---|---|---|---|
${rows.join("\n")}
`;

writeFileSync("docs/rules_report.md", md);
console.log(`Agreement: ${match}/${FIXTURES.length}. Wrote docs/rules_report.md`);
